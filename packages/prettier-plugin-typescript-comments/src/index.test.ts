import type { Parser, Plugin } from 'prettier';
import * as pluginOxc from '@prettier/plugin-oxc';
import { format, formatWithCursor } from 'prettier';
import { expect, expectTypeOf, onTestFinished, test, vi } from 'vite-plus/test';
import * as pluginTypeScriptComments from './index.ts';

const JAVASCRIPT_PARSER_NAMES = ['babel', 'oxc', 'oxc-ts', 'typescript'];

const TEST_JAVASCRIPT = `import { lazy } from 'react';
import styled from 'styled-components';

const invoices = await listInvoices(customerId, /* includeVoided */ false);

export const store = /* @__PURE__ */ createStore(reducer);

const SettingsPage = lazy(() => import(/* webpackChunkName: "settings" */ './pages/settings.js'));

const SESSION_TTL = /* matches the refresh window the identity provider enforces */ 900;

const DOCS_URL = "https://example.com/docs/comments#trailing";
const LINE_COMMENT_PATTERN = /\\/\\/.*$/m;
const banner = \`/* Generated by build.js on \${new Date().toISOString()} */\`;

const Card = styled.div\`
  /* Matches the gutter of the surrounding grid so cards line up with the page header */
  padding:16px;
\`;
`;

test('exposes correct public API', () => {
	expectTypeOf(pluginTypeScriptComments).toExtend<Plugin>();

	expect(pluginTypeScriptComments).toHaveProperty('parsers');

	expect(pluginTypeScriptComments.parsers).toHaveProperty('babel');
	expect(pluginTypeScriptComments.parsers).toHaveProperty('oxc');
	expect(pluginTypeScriptComments.parsers).toHaveProperty('oxc-ts');
	expect(pluginTypeScriptComments.parsers).toHaveProperty('typescript');
});

test.each(JAVASCRIPT_PARSER_NAMES)(
	'leaves code formatting to Prettier with the `%s` parser',
	async (parser) => {
		const options = {
			parser,
			printWidth: 40,
			singleQuote: true,
			useTabs: true,
		};

		const expectedOutput = await format(TEST_JAVASCRIPT, {
			...options,
			plugins: [pluginOxc],
		});

		const output = await format(TEST_JAVASCRIPT, {
			...options,
			plugins: [pluginOxc, pluginTypeScriptComments],
		});

		expect(output).toBe(expectedOutput);
		await expect(
			format(output, {
				...options,
				plugins: [pluginOxc, pluginTypeScriptComments],
			})
		).resolves.toBe(output);
	}
);

test('leaves out the `oxc` parsers when `@prettier/plugin-oxc` fails to load', async () => {
	vi.doMock('@prettier/plugin-oxc', () => {
		throw new Error('foo');
	});

	onTestFinished(() => {
		vi.doUnmock('@prettier/plugin-oxc');
	});

	vi.resetModules();
	const plugin = await import('./index.ts');

	expect(plugin.parsers).not.toHaveProperty('oxc');
	expect(plugin.parsers).not.toHaveProperty('oxc-ts');
});

test('adds an empty line after a shebang', async () => {
	const options = {
		parser: 'oxc-ts',
		plugins: [pluginOxc, pluginTypeScriptComments],
	};

	const output = await format('#!/usr/bin/env node\nfoo(  bar  )\n', options);

	expect(output).toBe('#!/usr/bin/env node\n\nfoo(bar);\n');
	await expect(format(output, options)).resolves.toBe(output);
});

test('formats code blocks in Markdown', async () => {
	const options = {
		parser: 'markdown',
		plugins: [pluginOxc, pluginTypeScriptComments],
	};

	const output = await format(
		'- foo\n\n  ```js\n  #!/usr/bin/env node\n  bar(  baz  )\n  ```\n',
		options
	);

	expect(output).toBe(
		'- foo\n\n  ```js\n  #!/usr/bin/env node\n\n  bar(baz);\n  ```\n'
	);
	await expect(format(output, options)).resolves.toBe(output);
});

test('respects `cursorOffset`', async () => {
	const input = '#!/usr/bin/env node\nfoo(  |bar  )\n';

	const result = await formatWithCursor(input.replace('|', ''), {
		cursorOffset: input.indexOf('|'),
		parser: 'oxc-ts',
		plugins: [pluginOxc, pluginTypeScriptComments],
	});

	expect(result.formatted.slice(result.cursorOffset)).toBe('bar);\n');
});

test.each(['cr', 'crlf'] as const)(
	'respects `endOfLine: %s`',
	async (endOfLine) => {
		const options = {
			endOfLine,
			parser: 'oxc-ts',
			plugins: [pluginOxc, pluginTypeScriptComments],
		};

		const output = await format(
			'#!/usr/bin/env node\nfoo(`\nbar\n`)\n',
			options
		);

		expect(output).toBe(
			'#!/usr/bin/env node\n\nfoo(`\nbar\n`);\n'.replaceAll(
				'\n',
				endOfLine === 'cr' ? '\r' : '\r\n'
			)
		);
		await expect(format(output, options)).resolves.toBe(output);
	}
);

test('respects `rangeStart` and `rangeEnd`', async () => {
	const input = '#!/usr/bin/env node\nfoo(  bar  )\nbaz(  qux  )\n';

	const expectedOutput = await format(input, {
		parser: 'oxc-ts',
		plugins: [pluginOxc],
		rangeEnd: 32,
		rangeStart: 20,
	});

	await expect(
		format(input, {
			parser: 'oxc-ts',
			plugins: [pluginOxc, pluginTypeScriptComments],
			rangeEnd: 32,
			rangeStart: 20,
		})
	).resolves.toBe(expectedOutput);
});

test('respects `rangeStart` and `rangeEnd` with `insertPragma`', async () => {
	const input = '/** @format */\nfoo(  bar  )\nbaz(  qux  )\n';
	const options = {
		insertPragma: true,
		parser: 'oxc-ts',
		rangeEnd: 27,
		rangeStart: 0,
	};

	const expectedOutput = await format(input, {
		...options,
		plugins: [pluginOxc],
	});

	await expect(
		format(input, {
			...options,
			plugins: [pluginOxc, pluginTypeScriptComments],
		})
	).resolves.toBe(expectedOutput);
});

