test.each(JAVASCRIPT_PARSER_NAMES)(
	'adds an empty line after a shebang when inserting a pragma with the `%s` parser',
	async (parser) => {
		const options = {
			insertPragma: true,
			parser,
			plugins: [pluginOxc, pluginTypeScriptComments],
		};

		const output = await format(
			'#!/usr/bin/env node\nfoo(  bar  )\n',
			options
		);

		expect(output).toBe(
			'#!/usr/bin/env node\n\n/** @format */\n\nfoo(bar);\n'
		);
		await expect(format(output, options)).resolves.toBe(output);
	}
);

test('respects `requirePragma`', async () => {
	const options = {
		parser: 'oxc-ts',
		plugins: [pluginOxc, pluginTypeScriptComments],
		requirePragma: true,
	};

	const input = '#!/usr/bin/env node\nfoo(  bar  )\n';

	await expect(format(input, options)).resolves.toBe(input);

	const output = await format(
		'#!/usr/bin/env node\n/** @format */\nfoo(  bar  )\n',
		options
	);

	expect(output).toBe('#!/usr/bin/env node\n\n/** @format */\nfoo(bar);\n');
	await expect(format(output, options)).resolves.toBe(output);
});

test('formats output from other plugins’ parser hooks', async () => {
	const testPlugin: Plugin = {
		parsers: {
			'oxc-ts': {
				astFormat: pluginOxc.parsers['oxc-ts'].astFormat,
				locEnd: pluginOxc.parsers['oxc-ts'].locEnd,
				locStart: pluginOxc.parsers['oxc-ts'].locStart,
				preprocess: async () => {
					await new Promise((resolve) => setTimeout(resolve));
					return '#!/usr/bin/env node\nfoo(  bar  )';
				},
			} as unknown as Parser,
		},
	};

	const emptyPlugin: Plugin = {};

	const options = {
		parser: 'oxc-ts',
		plugins: [pluginOxc, testPlugin, emptyPlugin, pluginTypeScriptComments],
	};

	const output = await format(TEST_JAVASCRIPT, options);

	expect(output).toMatchInlineSnapshot(`
		"#!/usr/bin/env node

		foo(bar);
		"
	`);
});
