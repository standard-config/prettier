test('supports `tsCommentWrap`', async () => {
	const input =
		'/*\n * foo   bar\n */\n// foo bar baz\n// qux\ncorge(); // grault\n';
	const options = {
		parser: 'oxc-ts',
		plugins: [pluginOxc, pluginTypeScript],
		printWidth: 20,
	};

	const outputs = {
		'all': await format(input, {
			...options,
			tsCommentWrap: 'all',
		}),
		'full-line': await format(input, {
			...options,
			tsCommentWrap: 'full-line',
		}),
		'none': await format(input, {
			...options,
			tsCommentWrap: 'none',
		}),
	};

	expect(outputs).toStrictEqual({
		'all': '/*\n * foo bar\n */\n// foo bar baz qux\n//\n// grault\ncorge();\n',
		'full-line':
			'/*\n * foo bar\n */\n// foo bar baz qux\ncorge(); // grault\n',
		'none': await format(input, {
			parser: 'oxc-ts',
			plugins: [pluginOxc],
			printWidth: 20,
		}),
	});
	await expect(format(outputs.all, options)).resolves.toBe(outputs.all);
	await expect(
		format(outputs['full-line'], {
			...options,
			tsCommentWrap: 'full-line',
		})
	).resolves.toBe(outputs['full-line']);
});
